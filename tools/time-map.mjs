async function writeFileAtomic(file, content) {
  await mkdir(path.dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.tmp`;
  await writeFile(temp, content, 'utf8');
  await rename(temp, file);
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const now = new Date();
  const since = new Date(now.getTime() - options.days * 86400000);
  const config = await loadConfig();
  const records = await extractSessions({ since });
  const aggregates = buildAggregates(records, config, options, since, now);
  const totalHours = aggregates.totals.hours;

  const sidecar = {
    title: 'Time Map',
    icon: 'chart',
    kind: 'report',
    created: now.toISOString(),
    note: `${one(aggregates.totals.minutes / 60)} h across ${aggregates.totals.sessions} sessions, last ${options.days} days`,
    svg: "<circle cx='24' cy='24' r='16'/><path d='M24 24V8'/><path d='M24 24l13 9'/>",
  };

  await writeFileAtomic(path.join(ARTIFACTS, 'time-map.html'), renderHtml(aggregates));
  await writeFileAtomic(path.join(ARTIFACTS, 'time-map.json'), `${JSON.stringify(sidecar, null, 2)}\n`);
  await writeFileAtomic(path.join(DATA, 'time-map.json'), `${JSON.stringify(aggregates, null, 2)}\n`);

  if (options.json) {
    process.stdout.write(`${JSON.stringify(aggregates, null, 2)}\n`);
    return;
  }
  console.log(`time-map: ${one(totalHours)} h, ${aggregates.totals.sessions} sessions, ${aggregates.totals.types} types -> artifacts/time-map.html`);
}

try {
  await main();
} catch (error) {
  console.error(`time-map: ${error.message || error}`);
  process.exitCode = 1;
}
