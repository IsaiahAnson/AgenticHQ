#!/usr/bin/env node
// Time Map: zero-token report on where agent session time goes, and which skills are worth building.
//   node tools/time-map.mjs [--days=28] [--json]
// Reads redacted session digests through ./ingest/sessions.mjs, classifies them with config/time-map.json,
// writes artifacts/time-map.html + artifacts/time-map.json (ring page) and data/time-map.json (aggregates).
// Sensitive digests carry no text: their time lands in one private bucket and nothing else about them is printed.
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractSessions } from './ingest/sessions.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG_FILE = path.join(ROOT, 'config', 'time-map.json');
const ARTIFACTS = path.join(ROOT, 'artifacts');
const DATA = path.join(ROOT, 'data');
const MAX_MINUTES = 180; // idle tabs: a session never counts more than 3 hours
const MIN_MINUTES = 2;
const MAX_PROMPT = 90;
const DEFAULT_FALLBACK = { id: 'other', label: 'Other', color: '#9E9E9E' };

function parseArgs(argv) {
  const options = { days: 28, json: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--json') options.json = true;
    else if (arg.startsWith('--days=')) options.days = Number(arg.slice(7));
    else if (arg === '--days') options.days = Number(argv[++i]);
    else throw new Error(`Unknown argument: ${arg}`);
  }
  if (!Number.isFinite(options.days) || options.days < 1) throw new Error('--days must be a positive number');
  options.days = Math.min(365, Math.round(options.days));
  return options;
}

const color = (value, fallback) => (/^#[0-9a-f]{3,8}$/i.test(String(value || '')) ? String(value) : fallback);

async function loadConfig() {
  let raw = {};
  try { raw = JSON.parse(await readFile(CONFIG_FILE, 'utf8')); } catch { raw = {}; }
  const types = (Array.isArray(raw.types) ? raw.types : [])
    .filter((type) => type && type.id)
    .map((type) => ({
      id: String(type.id),
      label: String(type.label || type.id),
      color: color(type.color, DEFAULT_FALLBACK.color),
      projects: (Array.isArray(type.projects) ? type.projects : []).map((item) => String(item).toLowerCase()),
      keywords: (Array.isArray(type.keywords) ? type.keywords : []).map((item) => String(item).toLowerCase()),
      skillHint: String(type.skillHint || ''),
    }));
  const fallback = {
    id: String(raw.fallback?.id || DEFAULT_FALLBACK.id),
    label: String(raw.fallback?.label || DEFAULT_FALLBACK.label),
    color: color(raw.fallback?.color, DEFAULT_FALLBACK.color),
  };
  return { types, fallback };
}

// A session takes the first type whose project substring or prompt keyword matches; otherwise the fallback.
// Hook-launched reviews and pings are not anyone's working time; dispatched workers are orchestration.
const AUTOMATED = /^(review this change for security|reply with just|reply with exactly|run '?git status'? with the bash tool)/i;
const WORKER = /dispatched worker|orca coordinator|you are working inside orca/i;
function classify(record, config) {
  const project = String(record.project || '').toLowerCase();
  const prompt = String(record.firstPrompt || '').toLowerCase();
  if (WORKER.test(prompt)) return config.types.find((type) => type.id === 'orchestration-handoffs') || config.fallback;
  for (const type of config.types) {
    if (type.projects.some((needle) => needle && project.includes(needle))) return type;
    if (type.keywords.some((needle) => needle && prompt.includes(needle))) return type;
  }
  return config.fallback;
}

function durationMinutes(record) {
  if (!record.started || !record.ended) return null;
  const start = Date.parse(record.started);
  const end = Date.parse(record.ended);
  if (!Number.isFinite(start) || !Number.isFinite(end) || end < start) return null;
  return Math.min(MAX_MINUTES, Math.max(MIN_MINUTES, (end - start) / 60000));
}

function isoWeek(value) {
  const date = new Date(value);
  if (Number.isNaN(date.valueOf())) return null;
  const day = new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate()));
  const weekday = day.getUTCDay() || 7;
  day.setUTCDate(day.getUTCDate() + 4 - weekday);
  const yearStart = new Date(Date.UTC(day.getUTCFullYear(), 0, 1));
  const week = Math.ceil(((day - yearStart) / 86400000 + 1) / 7);
  return `${day.getUTCFullYear()}-W${String(week).padStart(2, '0')}`;
}

// Harness wrappers and session plumbing make useless examples; skip them and keep looking.
const EXAMPLE_NOISE = /system-reminder|<local-command|<command-|^Caveat:|generated by the user while running|^name this chat|environment_context|<cwd>|<\/shell>|"filePath"|^\s*[[{]/i;

// Nothing that looks like a local user path or an email address survives into an example prompt.
function cleanPrompt(text) {
  let out = String(text || '').replace(/\s+/g, ' ').trim();
  if (!out || EXAMPLE_NOISE.test(out)) return '';
  out = out.replace(/\b[A-Za-z]:\s*[\\/][^\s"'<>|]*/g, '[path]');
  out = out.replace(/\bUsers[\\/][^\s"'<>|]*/g, '[path]');
  out = out.replace(/(^|\s)~[\\/][^\s"'<>|]*/g, '$1[path]');
  out = out.replace(/\\\\[^\s"'<>|]+/g, '[path]');
  out = out.replace(/\b[A-Za-z]:\s*(?=\[path\])/g, '');
  out = out.replace(/\b[\w.+-]+@[\w-]+\.[\w.-]+\b/g, '[email]');
  out = out.replace(/\s+/g, ' ').trim();
  if (out.length > MAX_PROMPT) out = `${out.slice(0, MAX_PROMPT - 1).trimEnd()}…`;
  return out;
}

const round = (value, places = 1) => Number(Number(value || 0).toFixed(places));
const hours = (minutes) => round(minutes / 60, 2);
const pct = (part, whole) => (whole > 0 ? round((part / whole) * 100, 1) : 0);

function buildAggregates(records, config, options, since, until) {
  const types = new Map();
  const projects = new Map();
  const agents = new Map();
  const weeks = new Map();
  let totalMinutes = 0;
  let sessionCount = 0;
  let sensitiveCount = 0;
  let toolErrors = 0;
  let skillSessions = 0;

  const bucket = (type) => {
    if (!types.has(type.id)) types.set(type.id, { id: type.id, label: type.label, color: type.color, skillHint: type.skillHint || '', minutes: 0, sessions: 0, toolErrors: 0, skillSessions: 0, examples: [] });
    return types.get(type.id);
  };

  for (const record of records) {
    const minutes = durationMinutes(record);
    if (minutes === null || AUTOMATED.test(String(record.firstPrompt || '').trim())) continue;
    const sensitive = record.sensitive === true;
    // Private digests have no text: they are typed by project folder only (never by content), else one private bucket.
    // They never add examples, project rows or agent rows.
    const project = String(record.project || '').toLowerCase();
    const byProject = sensitive && config.types.find((type) => type.id !== 'personal-admin' && type.projects.some((needle) => needle && project.includes(needle)));
    const type = sensitive
      ? byProject || { id: 'personal-admin-private', label: 'Private (privacy filter, untyped)', color: '#6f6a60', skillHint: 'Sessions the ingest privacy filter withheld (money, case or admin words anywhere in the text). No content is read, so they stay untyped.' }
      : classify(record, config);
    const entry = bucket(type);
    entry.minutes += minutes;
    entry.sessions += 1;
    totalMinutes += minutes;
    sessionCount += 1;

    if (!sensitive) {
      const errors = Number(record.toolErrors) || 0;
      entry.toolErrors += errors;
      toolErrors += errors;
      const usedSkill = Array.isArray(record.skillsUsed) && record.skillsUsed.length > 0;
      if (usedSkill) {
        entry.skillSessions += 1;
        skillSessions += 1;
      }
      if (entry.examples.length < 3 && record.firstPrompt) {
        const prompt = cleanPrompt(record.firstPrompt);
        if (prompt && !entry.examples.includes(prompt)) entry.examples.push(prompt);
      }
      const projectName = String(record.project || 'unknown');
      if (!projects.has(projectName)) projects.set(projectName, { project: projectName, minutes: 0, sessions: 0 });
      const projectRow = projects.get(projectName);
      projectRow.minutes += minutes;
      projectRow.sessions += 1;
    } else {
      sensitiveCount += 1;
    }

    const agentName = String(record.agent || 'unknown');
    if (!sensitive) {
      if (!agents.has(agentName)) agents.set(agentName, { agent: agentName, minutes: 0, sessions: 0 });
      const agentRow = agents.get(agentName);
      agentRow.minutes += minutes;
      agentRow.sessions += 1;
    }

    const week = isoWeek(record.started);
    if (week) {
      if (!weeks.has(week)) weeks.set(week, { week, minutes: 0, sessions: 0, types: new Map() });
      const weekRow = weeks.get(week);
      weekRow.minutes += minutes;
      weekRow.sessions += 1;
      weekRow.types.set(entry.id, (weekRow.types.get(entry.id) || 0) + minutes);
    }
  }

  const byType = [...types.values()]
    .map((type) => ({
      id: type.id,
      label: type.label,
      color: type.color,
      skillHint: type.skillHint,
      minutes: round(type.minutes),
      hours: hours(type.minutes),
      sessions: type.sessions,
      percent: pct(type.minutes, totalMinutes),
      toolErrors: type.toolErrors,
      errorsPerSession: round(type.sessions ? type.toolErrors / type.sessions : 0, 2),
      skillSessions: type.skillSessions,
      skillShare: round(type.sessions ? type.skillSessions / type.sessions : 0, 3),
      examples: type.examples,
    }))
    .sort((a, b) => b.minutes - a.minutes || a.label.localeCompare(b.label));

  const byProject = [...projects.values()]
    .map((row) => ({ project: row.project, minutes: round(row.minutes), hours: hours(row.minutes), sessions: row.sessions, percent: pct(row.minutes, totalMinutes) }))
    .sort((a, b) => b.minutes - a.minutes || a.project.localeCompare(b.project));

  const byAgent = [...agents.values()]
    .map((row) => ({
      agent: row.agent,
      minutes: round(row.minutes),
      hours: hours(row.minutes),
      sessions: row.sessions,
      percent: pct(row.minutes, totalMinutes),
      averageMinutes: round(row.sessions ? row.minutes / row.sessions : 0),
    }))
    .sort((a, b) => b.minutes - a.minutes || a.agent.localeCompare(b.agent));

  const byWeek = [...weeks.values()]
    .sort((a, b) => a.week.localeCompare(b.week))
    .map((row) => ({
      week: row.week,
      minutes: round(row.minutes),
      hours: hours(row.minutes),
      sessions: row.sessions,
      types: byType
        .filter((type) => row.types.has(type.id))
        .map((type) => ({ id: type.id, label: type.label, color: type.color, minutes: round(row.types.get(type.id)), hours: hours(row.types.get(type.id)) })),
    }));

  // A type is worth a skill when it eats time, mostly runs without a skill, and tends to throw tool errors.
  const suggestions = byType
    .map((type) => {
      const score = type.minutes * (1 - type.skillShare) * (1 + type.errorsPerSession / 5);
      return {
        typeId: type.id,
        label: type.label,
        color: type.color,
        skillHint: type.skillHint,
        minutes: type.minutes,
        hours: type.hours,
        sessions: type.sessions,
        skillShare: type.skillShare,
        errorsPerSession: type.errorsPerSession,
        score: round(score, 1),
        examples: type.examples.slice(0, 3),
      };
    })
    .sort((a, b) => b.score - a.score || b.minutes - a.minutes)
    .slice(0, 5);

  return {
    generated: new Date().toISOString(),
    range: { since: since.toISOString(), until: until.toISOString(), days: options.days },
    totals: {
      sessions: sessionCount,
      minutes: round(totalMinutes),
      hours: hours(totalMinutes),
      types: byType.length,
      projects: byProject.length,
      agents: byAgent.length,
      toolErrors,
      skillSessions,
      sensitiveSessions: sensitiveCount,
    },
    byType,
    byProject,
    byAgent,
    byWeek,
    suggestions,
  };
}

const esc = (value) => String(value ?? '').replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
const one = (value) => Number(value || 0).toFixed(1);
const num = (value) => (Number.isInteger(round(value, 1)) ? String(Math.round(value)) : one(value));
const shortDate = (iso) => new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric', timeZone: 'UTC' }).format(new Date(iso));
const yearOf = (iso) => new Intl.DateTimeFormat('en-US', { year: 'numeric', timeZone: 'UTC' }).format(new Date(iso));

function donutSvg(byType, totalMinutes) {
  const size = 220;
  const center = size / 2;
  const radius = 78;
  const stroke = 30;
  if (!byType.length || totalMinutes <= 0) {
    return `<svg class="donut" viewBox="0 0 ${size} ${size}" role="img" aria-label="No session time in this range"><circle cx="${center}" cy="${center}" r="${radius}" fill="none" stroke="#2c2822" stroke-width="${stroke}"/></svg>`;
  }
  const point = (degrees) => {
    const rad = (degrees * Math.PI) / 180;
    return [center + radius * Math.cos(rad), center + radius * Math.sin(rad)];
  };
  let angle = -90;
  const slices = byType.map((type) => {
    const sweep = (type.minutes / totalMinutes) * 360;
    const start = angle;
    const end = angle + sweep;
    angle = end;
    if (byType.length === 1) {
      return `<circle cx="${center}" cy="${center}" r="${radius}" fill="none" stroke="${esc(type.color)}" stroke-width="${stroke}"/>`;
    }
    const [x1, y1] = point(start);
    const [x2, y2] = point(end);
    const large = sweep > 180 ? 1 : 0;
    return `<path d="M${x1.toFixed(2)} ${y1.toFixed(2)}A${radius} ${radius} 0 ${large} 1 ${x2.toFixed(2)} ${y2.toFixed(2)}" fill="none" stroke="${esc(type.color)}" stroke-width="${stroke}" stroke-linecap="butt"/>`;
  });
  return `<svg class="donut" viewBox="0 0 ${size} ${size}" role="img" aria-label="Hours by task type">
        ${slices.join('\n        ')}
        <text x="${center}" y="${center - 2}" text-anchor="middle" class="donut-total">${one(totalMinutes / 60)}</text>
        <text x="${center}" y="${center + 20}" text-anchor="middle" class="donut-unit">hours</text>
      </svg>`;
}

function niceMax(value) {
  if (!(value > 0)) return 1;
  const power = Math.pow(10, Math.floor(Math.log10(value)));
  const scaled = value / power;
  const step = [1, 1.5, 2, 2.5, 3, 4, 5, 6, 8, 10].find((candidate) => scaled <= candidate) || 10;
  return step * power;
}

function weeklySvg(byWeek) {
  const width = Math.max(420, 84 + byWeek.length * 96);
  const height = 280;
  const baseline = 232;
  const chartHeight = 170;
  const maxHours = niceMax(Math.max(...byWeek.map((week) => week.minutes / 60), 0));
  const yFor = (value) => baseline - (value / maxHours) * chartHeight;
  const gridlines = [0, 0.5, 1].map((fraction) => {
    const y = yFor(maxHours * fraction);
    return `<line x1="64" y1="${y.toFixed(1)}" x2="${width - 16}" y2="${y.toFixed(1)}" stroke="#2c2822" stroke-width="1"/>
        <text x="54" y="${(y + 4).toFixed(1)}" text-anchor="end" class="axis">${num(maxHours * fraction)}</text>`;
  });
  const barWidth = 46;
  const bars = byWeek.map((week, index) => {
    const x = 82 + index * 96;
    let offset = 0;
    const parts = week.types.map((type) => {
      const h = (type.minutes / 60 / maxHours) * chartHeight;
      const y = baseline - offset - h;
      offset += h;
      return `<rect x="${x}" y="${y.toFixed(1)}" width="${barWidth}" height="${Math.max(h, 0.6).toFixed(1)}" fill="${esc(type.color)}"/>`;
    });
    return `<g>${parts.join('')}
        <text x="${x + barWidth / 2}" y="${baseline + 20}" text-anchor="middle" class="axis">${esc(week.week.replace(/^\d{4}-/, ''))}</text>
        <text x="${x + barWidth / 2}" y="${baseline + 38}" text-anchor="middle" class="axis dim">${one(week.minutes / 60)} h</text>
      </g>`;
  });
  return `<svg class="weeks" viewBox="0 0 ${width} ${height}" role="img" aria-label="Hours per week by task type">
        ${gridlines.join('\n        ')}
        ${bars.join('\n        ')}
        <line x1="64" y1="${baseline}" x2="${width - 16}" y2="${baseline}" stroke="#3a352d" stroke-width="1"/>
      </svg>`;
}

